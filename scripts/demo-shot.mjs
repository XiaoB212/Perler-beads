import puppeteer from 'puppeteer-core';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const errors = [];
const browser = await puppeteer.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: 'new', args: ['--no-sandbox','--disable-gpu','--hide-scrollbars'] });
const page = await browser.newPage();
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.setViewport({ width: 1440, height: 900, deviceScaleFactor: 2 });
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' });
await page.evaluate(() => localStorage.clear());
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle2' });
await sleep(1500);
const cls = await page.evaluate(() => [...document.querySelectorAll('canvas')].map(c => c.className + '|' + c.width + 'x' + c.height));
console.log('canvases:', JSON.stringify(cls));
const box = await page.evaluate(() => { const c = document.querySelector('.stage-canvas'); const r = c.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height }; });
console.log('stage box:', JSON.stringify(box));
await page.screenshot({ path: '.shots/review3/z-demo-new.png', clip: { x: box.x + box.w * 0.22, y: box.y + box.h * 0.12, width: box.w * 0.56, height: box.h * 0.72 } });
console.log('ERRORS:', errors.length ? [...new Set(errors)].join('|') : '(none)');
await browser.close();
